"""Working notes: a LaTeX document compiling all derivations, with immutable, tagged PDF versions.

notes/
  main.tex, sections/*.tex, refs.bib, figures/   living source (edited by agents)
  version.tex                                    generated stamp (git-ignored)
  build/                                         draft builds (git-ignored)
  versions/vNNN/                                 immutable releases:
      notes-vNNN.pdf, notes-vNNN.tex (flattened source), notes-vNNN-diff.pdf (vs previous), version.yaml
"""
from __future__ import annotations

import re
import shutil
import subprocess
from pathlib import Path

import yaml

from . import core

TEMPLATE = Path(__file__).resolve().parent.parent / "skills" / "notes" / "template"


def notes_dir() -> Path:
    return core.ROOT / "notes"


def versions_dir() -> Path:
    return notes_dir() / "versions"


def vcode(n: int) -> str:
    return f"v{n:03d}"


# ---------------------------------------------------------------- reading

def list_versions() -> list[dict]:
    d = versions_dir()
    out = []
    for p in sorted(d.glob("v[0-9]*"), reverse=True) if d.exists() else []:
        y = p / "version.yaml"
        meta = core.load_yaml(y.read_text()) if y.exists() else {}
        code = p.name
        files = {f.name: core.rel(f) for f in p.iterdir() if f.is_file()}
        out.append({
            "version": code, "n": int(code[1:]), "date": meta.get("date", ""), "author": meta.get("author", ""),
            "summary": meta.get("summary", ""), "changes": core.as_list(meta.get("changes")),
            "thread": meta.get("thread", ""), "pages": meta.get("pages", ""), "tag": meta.get("tag", ""),
            "commit": meta.get("commit", ""), "previous": meta.get("previous", ""),
            "pdf": files.get(f"notes-{code}.pdf"), "diff": files.get(f"notes-{code}-diff.pdf"),
            "tex": files.get(f"notes-{code}.tex"), "dir": core.rel(p),
        })
    return out


def get_version(code: str) -> dict | None:
    return next((v for v in list_versions() if v["version"] == code), None)


def draft_info() -> dict | None:
    pdf = notes_dir() / "build" / "main.pdf"
    if not pdf.exists():
        return None
    import datetime as dt
    return {"pdf": core.rel(pdf),
            "built": dt.datetime.fromtimestamp(pdf.stat().st_mtime).strftime("%Y-%m-%d %H:%M"),
            "pages": _pages(pdf)}


def _pages(pdf: Path) -> str:
    try:
        out = subprocess.run(["pdfinfo", str(pdf)], capture_output=True, text=True, timeout=20).stdout
        m = re.search(r"^Pages:\s+(\d+)", out, re.M)
        return m.group(1) if m else ""
    except (OSError, subprocess.TimeoutExpired):
        return ""


# ---------------------------------------------------------------- building

def init() -> Path:
    d = notes_dir()
    if (d / "main.tex").exists():
        raise ValueError("notes/main.tex already exists")
    shutil.copytree(TEMPLATE, d, dirs_exist_ok=True)
    (d / "figures").mkdir(exist_ok=True)
    main = d / "main.tex"
    name = "".join({"&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_", "{": r"\{", "}": r"\}",
                    "~": r"\textasciitilde{}", "^": r"\textasciicircum{}", "\\": r"\textbackslash{}"}.get(c, c)
                   for c in core.PROJECT_NAME)
    main.write_text(main.read_text().replace("@@PROJECT_NAME@@", name).replace("@@PORT@@", str(core.PORT)))
    return d


def _write_stamp(version: str, date: str, status: str) -> None:
    (notes_dir() / "version.tex").write_text(
        "% generated by ./dash notes, do not edit\n"
        f"\\def\\NotesVersion{{{version}}}\n\\def\\NotesDate{{{date}}}\n\\def\\NotesStatus{{{status}}}\n")


def _latexmk(src: str, outdir: str, cwd: Path) -> tuple[bool, str]:
    cmd = ["latexmk", "-pdf", "-interaction=nonstopmode", "-halt-on-error", "-file-line-error",
           f"-outdir={outdir}", src]
    try:
        res = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True, timeout=600)
    except (OSError, subprocess.TimeoutExpired) as e:
        return False, str(e)
    return res.returncode == 0, res.stdout + res.stderr


def log_problems(log_path: Path, limit: int = 25) -> list[str]:
    """Errors and the most useful warnings from a LaTeX .log."""
    if not log_path.exists():
        return ["no log file produced"]
    text = log_path.read_text(errors="replace")
    probs = []
    for m in re.finditer(r"^(?:\S+:\d+: |! ).*(?:\n.*){0,2}", text, re.M):
        probs.append("ERROR " + " ".join(m.group(0).split()))
    for pat in (r"^LaTeX Warning: (?:Reference|Citation) .*", r"^LaTeX Warning: There were undefined .*",
                r"^Package \w+ Warning: .*undefined.*"):
        probs += ["WARN " + w for w in re.findall(pat, text, re.M)]
    seen, out = set(), []
    for p in probs:
        if p not in seen:
            seen.add(p)
            out.append(p)
    return out[:limit]


def build(version: str | None = None, date: str | None = None) -> dict:
    """Compile notes/main.tex into notes/build/main.pdf. Returns {ok, pdf, problems, pages}."""
    d = notes_dir()
    if not (d / "main.tex").exists():
        raise ValueError("notes/main.tex not found: run `./dash notes init` first")
    last = list_versions()
    if version:
        _write_stamp(version, date or core.today(), "released version")
    else:
        base = f"after {last[0]['version']}" if last else "no released version yet"
        _write_stamp("DRAFT", core.now(), f"working draft ({base}), not a released version")
    ok, out = _latexmk("main.tex", "build", d)
    pdf = d / "build" / "main.pdf"
    problems = log_problems(d / "build" / "main.log")
    if not ok and not any(p.startswith("ERROR") for p in problems):
        problems = ["ERROR latexmk failed:"] + out.strip().splitlines()[-15:]
    return {"ok": ok and pdf.exists(), "pdf": core.rel(pdf) if pdf.exists() else "", "problems": problems,
            "pages": _pages(pdf) if pdf.exists() else ""}


STAMP_HOOK = r"\InputIfFileExists{version.tex}{}{}"
INPUT_RE = re.compile(r"^([^%\n]*?)\\(?:input|include)\{([^}]+)\}", re.M)


def flatten(path: Path, depth: int = 0) -> str:
    """Inline \\input/\\include recursively (paths relative to notes/)."""
    text = path.read_text()
    if depth > 10:
        return text

    def repl(m):
        name = m.group(2).strip()
        if name == "version":
            return m.group(0)
        f = notes_dir() / (name if name.endswith(".tex") else name + ".tex")
        return m.group(1) + (flatten(f, depth + 1) if f.exists() else m.group(0).split("\\", 1)[-1])
    return INPUT_RE.sub(repl, text)


def _git(*args) -> subprocess.CompletedProcess:
    return subprocess.run(["git", *args], cwd=core.ROOT, capture_output=True, text=True, timeout=60)


def release(summary: str, author: str, changes=None, thread: str = "", use_git: bool = True) -> dict:
    """Build, then freeze notes/versions/vNNN/ (+ diff vs previous), commit notes/ and tag notes-vNNN."""
    author = core._check_author(author)
    if not summary.strip():
        raise ValueError("a one-line summary (-m) is required")
    with core.locked():
        prev = list_versions()
        n = (prev[0]["n"] + 1) if prev else 1
        code = vcode(n)
        res = build(code, core.today())
        if not res["ok"]:
            errors = [p for p in res["problems"] if p.startswith("ERROR")] or res["problems"]
            raise ValueError("LaTeX build failed, nothing released:\n  " + "\n  ".join(errors))
        vd = versions_dir() / code
        vd.mkdir(parents=True)
        shutil.copy(notes_dir() / "build" / "main.pdf", vd / f"notes-{code}.pdf")
        stamp = (f"\\def\\NotesVersion{{{code}}}\\def\\NotesDate{{{core.today()}}}"
                 f"\\def\\NotesStatus{{released version}}% stamp inlined by ./dash notes release\n")
        flat = stamp + flatten(notes_dir() / "main.tex").replace(STAMP_HOOK, "% (version stamp inlined at top)")
        (vd / f"notes-{code}.tex").write_text(flat)

        diff_note = ""
        if prev and prev[0]["tex"]:
            diff_note = _make_diff(core.ROOT / prev[0]["tex"], vd / f"notes-{code}.tex", vd / f"notes-{code}-diff.pdf")

        commit = _git("rev-parse", "--short", "HEAD").stdout.strip() if use_git else ""
        meta = {"version": code, "date": core.now(), "author": author, "summary": summary.strip(),
                "changes": core.as_list(changes), "thread": str(thread or ""), "pages": res["pages"],
                "previous": prev[0]["version"] if prev else "", "tag": f"notes-{code}" if use_git else "",
                "built_from_commit": commit}
        (vd / "version.yaml").write_text(yaml.safe_dump(meta, sort_keys=False, allow_unicode=True, width=1000))
        build()  # leave the working build stamped as DRAFT again

    git_note = ""
    if use_git:
        _git("add", "notes")
        c = _git("commit", "-m", f"notes {code}: {summary.strip()}", "--", "notes")
        t = _git("tag", "-a", f"notes-{code}", "-m", f"Working notes {code}: {summary.strip()}")
        git_note = "committed + tagged" if c.returncode == 0 and t.returncode == 0 else \
            f"git problem: {(c.stderr or c.stdout or t.stderr).strip()[:300]}"
    return {"version": code, "dir": core.rel(vd), "pages": res["pages"], "diff": diff_note,
            "git": git_note, "warnings": [p for p in res["problems"] if p.startswith("WARN")]}


def _make_diff(old: Path, new: Path, out_pdf: Path) -> str:
    """latexdiff old->new, compiled in notes/build/diff (best effort)."""
    bd = notes_dir() / "build" / "diff"
    bd.mkdir(parents=True, exist_ok=True)
    try:
        res = subprocess.run(["latexdiff", "--math-markup=coarse", "--flatten", str(old), str(new)],
                             capture_output=True, text=True, timeout=300, cwd=notes_dir())
    except (OSError, subprocess.TimeoutExpired) as e:
        return f"diff skipped ({e})"
    if res.returncode != 0:
        return "diff skipped (latexdiff failed)"
    old_code = old.stem.replace("notes-", "")
    diff_tex = ("\\AtBeginDocument{\\def\\NotesStatus{CHANGES since " + old_code +
                ": \\textcolor{blue}{added}, \\textcolor{red}{removed}}}% added by ./dash notes\n" + res.stdout)
    (bd / "diff.tex").write_text(diff_tex)
    ok, _ = _latexmk("build/diff/diff.tex", "build/diff", notes_dir())
    pdf = bd / "diff.pdf"
    if ok and pdf.exists():
        shutil.copy(pdf, out_pdf)
        return "diff PDF created"
    return "diff skipped (diff did not compile)"
